/// Upstream `ChangedFormDataSizer`: the data of a changed form is never
/// compressed; the compressed size is its length.
pub fn changed_form_data_sizer(_a_base_ptr: DataPtr, a_element: ElementArg, compressed_size: &mut i32) -> u32 {
    const OFFSET_LENGTH: usize = 9;
    let Some(element) = a_element else {
        *compressed_size = 0;
        return 0;
    };
    let (size_length, changed_form) = changed_form_get_length_code(element);
    let Some(container) = changed_form.as_data_container().filter(|_| size_length >= 0) else {
        *compressed_size = 0;
        return 0;
    };
    match container.get_element_by_path("Datas\\CForm Data\\Length") {
        Some(length) => *compressed_size = native(Some(length)) as i32,
        None => {
            let data = container.get_data().unwrap_or_default();
            if let Some(value) = fo4saves::sized_value(data, OFFSET_LENGTH, size_length) {
                *compressed_size = value as i32;
            }
        }
    }
    0
}

