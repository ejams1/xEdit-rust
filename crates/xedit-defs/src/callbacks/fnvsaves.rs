/// Upstream `ChangedFormCellIsInteriorDecider`: an exterior cell has a
/// separator 0x20 bytes on.
pub fn changed_form_cell_is_interior_decider(a_base_ptr: DataPtr, a_element: ElementArg) -> i32 {
    /// Upstream `wbTerminator`.
    const TERMINATOR: u8 = b'|';
    let byte = match a_base_ptr.and_then(|data| data.get(0x20)) {
        Some(byte) => Some(*byte),
        // Upstream reads past the end of the data.
        None => a_element.and_then(|element| {
            let block = element.as_data_container()?.get_block()?;
            let start = address(a_base_ptr).checked_sub(block.as_ptr() as usize)?;
            block.get(start + 0x20).copied()
        }),
    };
    i32::from(byte.is_some_and(|byte| byte != TERMINATOR))
}

